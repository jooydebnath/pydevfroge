class NoneFrameworkProvider(Provider):
    name = "none-framework"
    display_name = "None"
    category = "framework"
    description = "No framework (plain Python)"
    capabilities = ["framework"]

    def generate(
        self, context: ProjectContext, project_dir: Path, files: dict[str, str]
    ) -> dict[str, str]:
        if context.framework not in ("none", "none-framework", "", None):
            return files
        files["src/__init__.py"] = ""
        files["src/main.py"] = (
            'def main():\n    print("hello")\n\nif __name__ == "__main__":\n    main()\n'
        )
        return files
